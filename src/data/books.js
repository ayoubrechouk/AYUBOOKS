const legacyBooks = MOCK_BOOKS.map((book) => ({
  id: book.id,
  title: book.title,
  author: book.writer,
  genre: book.genre,
  description: book.synopsis,
  coverId: openLibraryCoverIds[book.id],
  year: book.year,
  pages: book.pages,
}));

const newBooks = addedBooks.map(([title, author, genre, description], index) => ({
  id: `ayu-${String(index + 57).padStart(3, "0")}`,
  title,
  author,
  genre,
  description,
  coverId: openLibraryCoverIds[`ayu-${String(index + 57).padStart(3, "0")}`],
  year: addedBookYears[index],
  pages: 180 + ((index * 29) % 360),
}));

export const books = [...legacyBooks, ...newBooks].map((book) => ({
  ...book,
  posterUrl: `https://covers.openlibrary.org/b/id/${book.coverId}-L.jpg`,
}));

export const genres = ["All", ...new Set(books.map((book) => book.genre))];

export function getBookById(id) {
  return books.find((book) => book.id === id);
}
